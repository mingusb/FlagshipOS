"""Systemd-user lifecycle for the complete FlagshipOS provider set."""

from __future__ import annotations

import os
import json
from pathlib import Path
import shutil
import sys
import tempfile

from . import cli


TARGET = "flagship.target"
MARKER = "# Generated by FlagshipOS. Do not edit."
DEFAULT_PATH = "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"


def user_unit_dir():
    config_home = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")
    return config_home / "systemd" / "user"


def _escape(value):
    """Quote one systemd unit-file argument without invoking a shell."""
    if "\0" in value or "\n" in value or "\r" in value:
        raise cli.CommandError("Cannot write a systemd unit argument containing a control character.")
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%") + '"'


def _entry_command():
    invoked = Path(sys.argv[0])
    launcher = str(invoked.absolute()) if invoked.name == "flagship" and invoked.is_file() else None
    if launcher is None:
        launcher = shutil.which("flagship")
    if launcher:
        return [launcher]
    # Keep the active virtual-environment interpreter path; resolving its symlink
    # can escape the venv and lose the Flagship package.
    return [sys.executable, "-c", "from flagship.cli import main; raise SystemExit(main())"]


def _service_path():
    paths = DEFAULT_PATH.split(os.pathsep)
    for tool in ("podman", "distrobox"):
        executable = shutil.which(tool)
        if executable:
            directory = str(Path(executable).parent)
            if directory not in paths:
                paths.append(directory)
    return os.pathsep.join(paths)


def unit_files(ctx, catalog):
    base = _entry_command() + [f"--state-dir={ctx.state_dir}", f"--workspace={ctx.workspace}"]
    profiles = tuple(catalog)
    target = "\n".join([
        MARKER,
        "[Unit]",
        "Description=FlagshipOS seven-provider session",
        "Requires=" + " ".join(f"flagship-{profile}.service" for profile in profiles),
        "After=" + " ".join(f"flagship-{profile}.service" for profile in profiles),
        "StartLimitIntervalSec=0",
        "",
        "[Install]",
        "WantedBy=default.target",
        "",
    ])
    environment = _service_path()
    files = {TARGET: target}
    for profile in profiles:
        start = base + ["run", profile, "--", "sleep", "infinity"]
        stop = base + ["--_service-stop", profile]
        lines = [
            MARKER,
            "[Unit]",
            f"Description=FlagshipOS {profile} provider",
            f"PartOf={TARGET}",
            "StartLimitIntervalSec=0",
            "",
            "[Service]",
            "Type=exec",
            f"Environment=HOME={_escape(str(Path.home()))}",
            f"Environment=PATH={_escape(environment)}",
            "ExecStart=" + " ".join(_escape(arg) for arg in start),
            "ExecStop=" + " ".join(_escape(arg) for arg in stop),
            "Restart=always",
            "RestartSec=5s",
            "TimeoutStopSec=45s",
            "KillMode=mixed",
            "",
        ]
        files[f"flagship-{profile}.service"] = "\n".join(lines)
    return files


def _write_unit_files(ctx, catalog):
    directory = user_unit_dir()
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    files = unit_files(ctx, catalog)
    existing_files = {}
    for name, content in files.items():
        destination = directory / name
        if destination.is_symlink() or (destination.exists() and not destination.is_file()):
            raise cli.CommandError(f"Refusing to replace a non-regular systemd unit: {destination}")
        if destination.exists():
            try:
                existing = destination.read_text("utf-8")
            except (OSError, UnicodeError) as exc:
                raise cli.CommandError(f"Cannot read existing systemd unit: {destination}") from exc
            if not existing.startswith(MARKER + "\n"):
                raise cli.CommandError(f"Refusing to replace an unmanaged systemd unit: {destination}")
            existing_files[name] = existing
    for name, content in files.items():
        destination = directory / name
        if existing_files.get(name) == content:
            continue
        staged = None
        try:
            with tempfile.NamedTemporaryFile("w", encoding="utf-8", newline="\n", dir=directory,
                                             prefix=".flagship-", delete=False) as temporary:
                temporary.write(content)
                temporary.flush()
                os.fsync(temporary.fileno())
                staged = Path(temporary.name)
            os.chmod(staged, 0o644)
            os.replace(staged, destination)
        except OSError as exc:
            try:
                if staged is not None:
                    staged.unlink(missing_ok=True)
            except OSError:
                pass
            raise cli.CommandError(f"Cannot write systemd unit {destination}: {exc}") from exc
    return directory


def _systemctl(arguments, *, check=True):
    executable = shutil.which("systemctl")
    if not executable:
        raise cli.CommandError("systemctl is unavailable; Flagship lifecycle management needs systemd.")
    result = cli.capture([executable, "--user", *arguments], check=False)
    if check and result.returncode:
        detail = result.stderr.strip() or result.stdout.strip() or f"exit {result.returncode}"
        if "bus" in detail.lower() or "system has not been booted with systemd" in detail.lower():
            detail += " On WSL, enable systemd in /etc/wsl.conf; use 'flagship autostart enable --linger' to start the user manager before login."
        raise cli.CommandError(f"systemctl --user {' '.join(arguments)} failed: {detail}", cli.exit_code(result.returncode))
    return result


def _validate_all(ctx, catalog):
    errors = []
    for profile in catalog:
        try:
            cli.managed_container(ctx, profile)
        except cli.CommandError as exc:
            errors.append(f"{profile}: {exc}")
    if errors:
        details = "\n".join(f"  - {error}" for error in errors)
        raise cli.CommandError("FlagshipOS requires all seven providers; create and verify each one before booting:\n" + details)


def _load_units(ctx, catalog):
    directory = _write_unit_files(ctx, catalog)
    _systemctl(["daemon-reload"])
    return directory


def _require_user_manager():
    _systemctl(["show-environment"])


def _enable_linger():
    import pwd
    user = pwd.getpwuid(os.getuid()).pw_name
    status = cli.capture(["loginctl", "show-user", user, "--property=Linger"], check=False)
    if status.returncode == 0 and "Linger=yes" in status.stdout.splitlines():
        return
    cli.checked_stream(["sudo", "loginctl", "enable-linger", user])


def _stop_owned(ctx, profile):
    if profile not in cli.load_catalog():
        raise cli.CommandError("Unknown provider in FlagshipOS service request.", 2)
    container = cli.inspect_container(f"flagship-{profile}")
    if container is None:
        return 0
    cli.ensure_owned(ctx, profile, container)
    cli.checked_stream(["podman", "stop", "--time", "15", f"flagship-{profile}"])
    return 0


def _stop_all_owned(ctx, catalog):
    errors = []
    for profile in catalog:
        name = f"flagship-{profile}"
        try:
            container = cli.inspect_container(name)
            if container is None:
                continue
            cli.ensure_owned(ctx, profile, container)
            if container.get("State", {}).get("Status") == "running":
                cli.checked_stream(["podman", "stop", "--time", "15", name])
                stopped = cli.inspect_container(name)
                if stopped and stopped.get("State", {}).get("Status") == "running":
                    errors.append(f"{profile}: container remained running")
        except cli.CommandError as exc:
            errors.append(f"{profile}: {exc}")
    if errors:
        details = "\n".join(f"  - {error}" for error in errors)
        raise cli.CommandError("Could not stop every FlagshipOS provider:\n" + details)


def _provider_states(catalog):
    return {profile: _systemctl(["is-active", f"flagship-{profile}.service"], check=False).returncode == 0
            for profile in catalog}


def _require_all_active(catalog):
    states = _provider_states(catalog)
    failed = [profile for profile, active in states.items() if not active]
    if failed:
        detail = ", ".join(failed)
        raise cli.CommandError(f"FlagshipOS did not bring up every provider; inactive services: {detail}. "
                               "Inspect them with 'journalctl --user -u flagship-PROFILE.service'.")


def _plan(ctx, args, catalog):
    files = unit_files(ctx, catalog)
    commands = {
        "boot": [["systemctl", "--user", "daemon-reload"], ["systemctl", "--user", "start", TARGET]],
        "shutdown": [["systemctl", "--user", "stop", TARGET]],
        "restart": [["systemctl", "--user", "stop", TARGET], ["systemctl", "--user", "start", TARGET]],
    }
    if args.command == "autostart":
        if args.action == "enable":
            commands["autostart"] = [["systemctl", "--user", "daemon-reload"],
                                     ["systemctl", "--user", "enable", TARGET]]
            if args.linger:
                commands["autostart"].insert(0, ["sudo", "loginctl", "enable-linger", "${USER}"])
        elif args.action == "disable":
            commands["autostart"] = [["systemctl", "--user", "disable", TARGET]]
        else:
            commands["autostart"] = [["systemctl", "--user", "is-enabled", TARGET]]
    key = args.command if args.command != "autostart" else "autostart"
    print(json.dumps({
        "operation": f"{args.command} {getattr(args, 'action', '')}".strip(),
        "requires_all_profiles": list(catalog),
        "unit_directory": str(user_unit_dir()),
        "unit_files": files,
        "commands": commands[key],
        "notes": ["Dry run: no systemd units or running services are changed."],
    }, indent=2))
    return 0


def main(ctx, args, catalog):
    if args.dry_run:
        return _plan(ctx, args, catalog)
    if args.command == "_service-stop":
        return _stop_owned(ctx, args.profile)

    if args.command in ("boot", "restart") or (args.command == "autostart" and args.action == "enable"):
        _validate_all(ctx, catalog)
    if args.command == "autostart" and args.action == "enable" and args.linger:
        _enable_linger()
    _require_user_manager()
    if args.command != "autostart" or args.action != "status":
        _load_units(ctx, catalog)

    if args.command == "boot":
        _systemctl(["start", TARGET])
        _require_all_active(catalog)
        print("FlagshipOS is running with all seven providers.")
    elif args.command == "shutdown":
        _systemctl(["stop", TARGET])
        _stop_all_owned(ctx, catalog)
        print("FlagshipOS providers have been stopped; their containers and files are preserved.")
    elif args.command == "restart":
        _systemctl(["stop", TARGET])
        _stop_all_owned(ctx, catalog)
        _systemctl(["start", TARGET])
        _require_all_active(catalog)
        print("FlagshipOS restarted with all seven providers.")
    elif args.command == "autostart":
        if args.action == "enable":
            _systemctl(["enable", TARGET])
            _systemctl(["start", TARGET])
            _require_all_active(catalog)
            if args.linger:
                print("FlagshipOS will start all seven providers when WSL starts, before an interactive login.")
            else:
                print("FlagshipOS will start all seven providers when the user systemd manager starts.")
        elif args.action == "disable":
            _systemctl(["disable", TARGET])
            print("FlagshipOS autostart is disabled; currently running providers are unchanged.")
        else:
            enabled = _systemctl(["is-enabled", TARGET], check=False)
            active = _systemctl(["is-active", TARGET], check=False)
            print(f"Autostart: {'enabled' if enabled.returncode == 0 else 'disabled'}")
            states = _provider_states(catalog)
            all_active = active.returncode == 0 and all(states.values())
            print(f"Provider set: {'all seven running' if all_active else 'incomplete or stopped'}")
            for profile, provider_active in states.items():
                print(f"  {profile}: {'running' if provider_active else 'stopped'}")
            return 0
    return 0
